import fs from 'node:fs/promises';
import sharp from 'sharp';
import {spriteComponents} from './act-two-components.mjs';
const dir='context/arcade/nightmare-madness-v2',out='public/arcade/act-two/nightmare-madness-v2';
await fs.mkdir(out,{recursive:true});await fs.mkdir(dir+'/sources',{recursive:true});
const manifest=JSON.parse(await fs.readFile(dir+'/art-sources.json','utf8')),registration={};
for(const item of manifest){
 const source=dir+'/sources/'+item.name+'.png';
 try{await fs.access(source);}catch{await fs.copyFile(item.source,source);}
}
for(const item of manifest){
 const source=dir+'/sources/'+item.name+'.png';
 if(item.selected===false)continue;
 const name=item.name.replace(/-alpha$/,'');
 if(['madness-portrait','charge-portrait','candy-warehouse'].includes(name)){
  await sharp(source).webp({lossless:true}).toFile(out+'/'+name+'.webp');continue;
 }
 const rows=name.endsWith('-walk')?3:name==='candy-props'?2:4,count=rows*4;
 const {data,info,labels,components}=await spriteComponents(source);let boxes,replacement;
 if(name==='candy-props'){
  // Keep the disconnected sweets belonging to each isolated pile together.
  boxes=Array.from({length:count},(_,i)=>({left:Math.floor(i%4*info.width/4),top:Math.floor(Math.floor(i/4)*info.height/rows),width:Math.floor(info.width/4),height:Math.floor(info.height/rows),grid:true}));
 }else{
  const bodies=components.filter(q=>q.area>1500).sort((a,b)=>b.area-a.area).slice(0,count).sort((a,b)=>a.cy-b.cy);
  if(name==='phase-two'&&bodies.length===15){
   // Two poses touched in the source sheet. Replace BOTH with independently
   // redrawn whole poses instead of slicing through a shared staff/boot edge.
   replacement=await spriteComponents(dir+'/sources/phase-two-bow-leap.png');
   const pair=replacement.components.filter(q=>q.area>1500).sort((a,b)=>b.area-a.area).slice(0,2).sort((a,b)=>a.cx-b.cx).map(q=>({...q,replacement:true}));
   const solo=bodies.filter(q=>q.height<info.height*.35);if(solo.length!==14||pair.length!==2)throw Error('Unregistered phase-two replacement poses');
   boxes=[...solo.slice(0,4).sort((a,b)=>a.cx-b.cx),...solo.slice(4,7).sort((a,b)=>a.cx-b.cx),pair[0],...solo.slice(7,10).sort((a,b)=>a.cx-b.cx),pair[1],...solo.slice(10).sort((a,b)=>a.cx-b.cx)];
  }else{
   if(bodies.length!==count)throw Error(name+': expected '+count+' separate whole characters, got '+bodies.length);
   boxes=[];for(let row=0;row<rows;row++)boxes.push(...bodies.slice(row*4,row*4+4).sort((a,b)=>a.cx-b.cx));
  }
 }
 // Replacement poses have a different source resolution; match their body
 // height to the main sheet before applying its common runtime scale.
 const referenceHeight=Math.max(...boxes.filter(q=>!q.replacement).map(q=>q.height)),scale=Math.min(430/referenceHeight,480/Math.max(...boxes.filter(q=>!q.replacement).map(q=>q.width))),parts=[];
 registration[name]=[];
 for(const [frame,q]of boxes.entries()){
  const pixels=q.replacement?replacement.data:data,sourceInfo=q.replacement?replacement.info:info,sourceLabels=q.replacement?replacement.labels:labels;
  const rgba=Buffer.alloc(q.width*q.height*4);
  for(let y=0;y<q.height;y++)for(let x=0;x<q.width;x++){
   const at=(y+q.top)*sourceInfo.width+x+q.left;
   if(!q.grid&&sourceLabels[at]!==q.id)continue;
   pixels.copy(rgba,(y*q.width+x)*4,at*4,at*4+4);
  }
  let img=sharp(rgba,{raw:{width:q.width,height:q.height,channels:4}});
  const poseScale=q.replacement?Math.min(430/q.height,480/q.width):scale;
  let w=Math.round(q.width*poseScale),h=Math.round(q.height*poseScale);
  if(q.grid){const trimmed=await img.trim({threshold:10}).png().toBuffer();const meta=await sharp(trimmed).metadata();w=Math.round(meta.width*Math.min(440/meta.width,420/meta.height));h=Math.round(meta.height*Math.min(440/meta.width,420/meta.height));img=sharp(trimmed);}
  const input=await img.resize(w,h).png().toBuffer(),left=Math.round((512-w)/2),top=499-h;
  parts.push({input,left:frame%4*512+left,top:Math.floor(frame/4)*512+top});
  const tip={x:left+w*(frame===5?.075:frame===6?.2:.16),y:top+h*(frame===5?.36:frame===6?.08:.22)};
  registration[name].push({source:q,left,top,w,h,tip});
 }
 await sharp({create:{width:2048,height:512*rows,channels:4,background:'#00000000'}}).composite(parts).webp({lossless:true}).toFile(out+'/'+name+'.webp');
}
await fs.writeFile(dir+'/registration.json',JSON.stringify(registration,null,2)+'\n');
const sockets=Object.fromEntries(Object.entries(registration).filter(([k])=>k.startsWith('phase-')).map(([k,v])=>['nightmare-'+k,v.map(q=>[q.tip.x,q.tip.y])]));
await fs.writeFile('src/components/arcade/adventure/actors/bosses/nightmareRegistration.js','// Generated by pack-nightmare-madness.mjs; isolated 512px cels.\nexport const NIGHTMARE_MUZZLES='+JSON.stringify(sockets)+';\n');
console.log('Packed nightmare phases, portraits and candy warehouse.');
