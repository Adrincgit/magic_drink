import fs from 'node:fs';
import sharp from 'sharp';

// Preserve native detail and alpha. Roots, rather than the canopy center,
// determine the world pivot and the terrain footprint of each cutout.
const folder='public/arcade/maps/riverwoods/trees/';
const measurements={};
for(const name of ['oak','willow','birch','hawthorn']){
 const file=folder+name+'.webp';
 const {data,info}=await sharp(file).ensureAlpha().raw().toBuffer({resolveWithObject:true});
 let left=info.width,right=0;
 for(let y=Math.floor(info.height*.88);y<info.height;y++)for(let x=0;x<info.width;x++){
  if(data[(y*info.width+x)*4+3]<128)continue;
  left=Math.min(left,x);right=Math.max(right,x);
 }
 if(left>=right)throw Error('Missing roots: '+name);
 measurements['river-tree-'+name]={width:info.width,height:info.height,rootX:(left+right)/2/info.width,rootLeft:left/info.width,rootRight:right/info.width};
}
fs.writeFileSync('src/components/arcade/adventure/world/riverTreeArt.js',
 '// Native tree dimensions and measured root pivots. Generated by pack-river-trees.mjs.\n'+
 'export const RIVER_TREE_ART='+JSON.stringify(measurements,null,2)+';\n');
console.log(measurements);
