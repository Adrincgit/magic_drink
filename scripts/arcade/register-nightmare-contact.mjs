import fs from 'node:fs/promises';
import sharp from 'sharp';

// Register the painted luminous cores, not the transparent atlas edges.
// Keep every original pixel, including the tapered rim and star filaments.
async function cores(file,cols,count,region){
 const {data,info}=await sharp(file).ensureAlpha().raw().toBuffer({resolveWithObject:true});
 const w=info.width/cols,h=info.height/Math.ceil(count/cols),points=[];
 for(let f=0;f<count;f++){
  let sx=0,sy=0,sum=0;
  for(let y=Math.floor(h*region[1]);y<h*region[3];y++)for(let x=Math.floor(w*region[0]);x<w*region[2];x++){
   const p=((Math.floor(f/cols)*h+y)*info.width+f%cols*w+x)*4;
   const white=Math.min(data[p],data[p+1],data[p+2]),weight=Math.max(0,white-220)**3*data[p+3]/255;
   sx+=x*weight;sy+=y*weight;sum+=weight;
  }
  if(!sum)throw Error('Missing luminous core: '+file+':'+f);
  points.push([+(sx/sum).toFixed(3),+(sy/sum).toFixed(3)]);
 }
 return points;
}
const star=await cores('public/arcade/sprites/effects/super-beam-rotation.webp',1,12,[.84,.32,.98,.68]);
const vortex=await cores('public/arcade/act-two/nightmare-performance-v10/halloween-vortex-16.webp',4,16,[.06,.34,.23,.66]);
const plasma=await cores('public/arcade/act-two/nightmare-performance-v10/clash-plasma.webp',4,8,[.32,.32,.68,.68]);
const file='src/components/arcade/adventure/render/nightmareContactRegistration.js';
await fs.writeFile(file,`// Generated by scripts/arcade/register-nightmare-contact.mjs from the painted cores.\nexport const NIGHTMARE_STAR_CORES=${JSON.stringify(star)};\nexport const NIGHTMARE_VORTEX_CORES=${JSON.stringify(vortex)};\nexport const NIGHTMARE_PLASMA_CORES=${JSON.stringify(plasma)};\n`);
console.log('Registered 12 star, 16 vortex and 8 contact cels without altering artwork.');
