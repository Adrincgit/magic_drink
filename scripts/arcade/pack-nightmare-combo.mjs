import fs from 'node:fs/promises';
import sharp from 'sharp';
import {spriteComponents} from './act-two-components.mjs';
const dir='context/arcade/nightmare-combo-v9',out='public/arcade/act-two/nightmare-combo-v9';
await fs.mkdir(out,{recursive:true});
const stature=JSON.parse(await fs.readFile('context/arcade/nightmare-coherence-v7/registration.json','utf8')).reference.targetHeight;
const body={},tips={},vortex=[];
async function frames(file){
 const s=await spriteComponents(file),boxes=s.components.filter(q=>q.area>10000).sort((a,b)=>b.area-a.area).slice(0,8).sort((a,b)=>a.cy-b.cy),ordered=[];
 if(boxes.length!==8)throw Error('Expected eight complete connected cels: '+file);
 for(let row=0;row<2;row++)ordered.push(...boxes.slice(row*4,row*4+4).sort((a,b)=>a.cx-b.cx));
 return Promise.all(ordered.map(async q=>{
  const pad=12,left=Math.max(0,q.left-pad),top=Math.max(0,q.top-pad),width=Math.min(s.info.width-left,q.width+pad*2),height=Math.min(s.info.height-top,q.height+pad*2),rgba=Buffer.alloc(width*height*4);
  for(let y=0;y<height;y++)for(let x=0;x<width;x++){
   const p=(y+top)*s.info.width+x+left;
   if(s.labels[p]===q.id||s.data[p*4+3]>0&&s.data[p*4+3]<=32)s.data.copy(rgba,(y*width+x)*4,p*4,p*4+4);
  }
  return{input:await sharp(rgba,{raw:{width,height,channels:4}}).png().toBuffer(),w:width,h:height,box:q};
 }));
}
for(const phase of [2,3]){
 const key='nightmare-staff-down-'+phase,source=await frames(dir+'/sources/staff-down-'+phase+'.png'),scale=Math.min(440/Math.max(...source.map(q=>q.h)),460/Math.max(...source.map(q=>q.w))),size=512*stature/(source[7].box.height*scale),parts=[];
 body[key]=[];tips[key]=[];
 for(const [i,q]of source.entries()){
  const w=Math.round(q.w*scale),h=Math.round(q.h*scale),left=Math.round((512-w)/2),top=499-h,input=await sharp(q.input).resize(w,h).png().toBuffer();
  parts.push({input,left:i%4*512+left,top:Math.floor(i/4)*512+top});body[key].push({size,offsetX:0});
  const rgba=await sharp(input).ensureAlpha().raw().toBuffer();let sx=0,sy=0,n=0,bottom=0;
  for(let y=0;y<h;y++)for(let x=0;x<w;x++){
   const p=(y*w+x)*4,[r,g,b,a]=rgba.subarray(p,p+4);
   if(a>150&&r>190&&g>115&&b<110&&x<w*.35&&(i===4||i===5?y>h*.65:true)){sx+=x;sy+=y;n++;bottom=Math.max(bottom,y);}
  }
  tips[key].push(n?[left+sx/n,top+(i===4||i===5?bottom:sy/n)]:[left+w*.2,top+h*.8]);
 }
 await sharp({create:{width:2048,height:1024,channels:4,background:'#0000'}}).composite(parts).webp({lossless:true}).toFile(out+'/staff-down-'+phase+'.webp');
}
{
 const source=await frames(dir+'/sources/moon-storm.png'),scale=Math.min(420/Math.max(...source.map(q=>q.h)),444/Math.max(...source.map(q=>q.w))),parts=[];
 for(const [i,q]of source.entries()){
  const w=Math.round(q.w*scale),h=Math.round(q.h*scale),left=Math.round((512-w)/2),top=Math.round((512-h)/2);
  parts.push({input:await sharp(q.input).resize(w,h).png().toBuffer(),left:i%4*512+left,top:Math.floor(i/4)*512+top});
  // Register the complete outer rim. No intermediate rectangular bake or
  // crop is permitted between this rounded silhouette and the clash.
  vortex.push({front:[left+12*scale,256],tail:[left+w-12*scale,256]});
 }
 await sharp({create:{width:2048,height:1024,channels:4,background:'#0000'}}).composite(parts).webp({lossless:true}).toFile(out+'/moon-storm.webp');
}
await fs.writeFile('src/components/arcade/adventure/actors/bosses/nightmareComboRegistration.js','// Generated by pack-nightmare-combo.mjs; complete drawn cels and spell silhouettes.\nexport const NIGHTMARE_COMBO_BODY='+JSON.stringify(body)+';\nexport const NIGHTMARE_COMBO_STAFF_TIPS='+JSON.stringify(tips)+';\nexport const NIGHTMARE_COMBO_VORTEX_SOCKETS='+JSON.stringify(vortex)+';\n');
await fs.writeFile(dir+'/registration.json',JSON.stringify({body,tips,vortex},null,2)+'\n');
console.log('Packed 16 descending staff drawings and 8 complete face-free vortex cels.');
