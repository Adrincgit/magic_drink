import fs from 'node:fs/promises';
import sharp from 'sharp';
import {spriteComponents} from './act-two-components.mjs';
const dir='context/arcade/cornfield-cartoon-v3',out='public/arcade/act-two/cornfield-cartoon-v3';
await fs.mkdir(out,{recursive:true});
const cell=512,foot=499,registration={},muzzles={},walkSizes={};
const sourcePoints={king:{4:[280,44],5:[24,92],6:[-34,95],7:[-12,100]},harvest:{4:[40,203],5:[124,20],6:[24,199],7:[40,163],8:[100,70],9:[94,28],10:[44,105],11:[15,155]},imp:{14:[20,110]}};
for(const name of ['king','harvest','imp','flock','king-walk','harvest-walk']){
 const walking=name.endsWith('-walk'),rows=walking?3:4,src=await spriteComponents(dir+'/sources/'+name+'.png'),{data,info,labels}=src;
 const sourceW=info.width/4,sourceH=info.height/rows,groups=Array.from({length:4*rows},()=>[]);
 for(const q of src.components)if(q.area>10)groups[Math.min(rows-1,Math.floor(q.cy/sourceH))*4+Math.min(3,Math.floor(q.cx/sourceW))].push(q);
 const primary=groups.map((group,frame)=>{const p=group.toSorted((a,b)=>b.area-a.area)[0];if(!p||p.area<500)throw Error(`Missing ${name}:${frame}`);return p;});
 const walkScale=1,parts=[];registration[name]=[];muzzles[name]={};
 if(walking)walkSizes[name]=(name==='king-walk'?410:452)*244/384*cell/Math.max(...primary.map(q=>q.height));
 for(let frame=0;frame<groups.length;frame++){
  const ids=new Set(groups[frame].map(q=>q.id)),mask=new Uint8Array(labels.length);
  for(const q of groups[frame])for(let y=q.top;y<q.top+q.height;y++)for(let x=q.left;x<q.left+q.width;x++)if(ids.has(labels[y*info.width+x]))for(let dy=-1;dy<=1;dy++)for(let dx=-1;dx<=1;dx++){
   const xx=x+dx,yy=y+dy;if(xx>=0&&xx<info.width&&yy>=0&&yy<info.height)mask[yy*info.width+xx]=1;
  }
  const rgba=Buffer.from(data);for(let i=0;i<mask.length;i++)if(!mask[i])rgba[i*4+3]=0;
  let input,record;
  if(walking){
   const q=primary[frame],width=Math.round(q.width*walkScale),height=Math.round(q.height*walkScale);
   const actor=await sharp(rgba,{raw:info}).extract({left:q.left,top:q.top,width:q.width,height:q.height}).resize(width,height).png().toBuffer();
   const left=Math.round((cell-width)/2),top=foot-height;
   input=await sharp({create:{width:cell,height:cell,channels:4,background:'#00000000'}}).composite([{input:actor,left,top}]).png().toBuffer();record={source:q,scale:walkScale,left,top};
  }else{
   const col=frame%4,row=Math.floor(frame/4),top=name==='flock'?128:500-(primary[frame].top+primary[frame].height-row*sourceH);
   const left=col*sourceW-64,sourceTop=row*sourceH-top,padded=Buffer.alloc(512*512*4);
   for(let y=0;y<512;y++)for(let x=0;x<512;x++){
    const sx=Math.round(x+left),sy=Math.round(y+sourceTop);if(sx<0||sy<0||sx>=info.width||sy>=info.height)continue;
    const from=(sy*info.width+sx)*4;rgba.copy(padded,(y*512+x)*4,from,from+4);
   }
   input=await sharp(padded,{raw:{width:cell,height:cell,channels:4}}).png().toBuffer();record={sourceCell:[sourceW,sourceH],top,paddingX:64,scale:1};
   const p=sourcePoints[name]?.[frame];if(p)muzzles[name][frame]=[p[0]+64,p[1]+top];
  }
  parts.push({input,left:frame%4*cell,top:Math.floor(frame/4)*cell});registration[name].push(record);
 }
 await sharp({create:{width:cell*4,height:rows*cell,channels:4,background:'#00000000'}}).composite(parts).webp({lossless:true}).toFile(out+'/'+name+'.webp');
}
await fs.writeFile(dir+'/registration.json',JSON.stringify({cell,sourcePoints,registration,muzzles,walkSizes},null,2)+'\n');
await fs.writeFile('src/components/arcade/adventure/actors/cornfieldCartoonRegistration.js','// Generated by pack-cornfield-cartoon-v3.mjs. Native pixels, 512px cels face LEFT.\nexport const CORN_CARTOON_CELL='+cell+';\nexport const CORN_CARTOON_WALK_SIZE='+JSON.stringify(walkSizes)+';\nexport const CORN_CARTOON_MUZZLES='+JSON.stringify(muzzles)+';\n');
console.log('Six anime-cartoon character/effect atlases packed, 88 cels; registered hands and pitchfork points.');
