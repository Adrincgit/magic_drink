import fs from 'node:fs/promises';
import sharp from 'sharp';
import {spriteComponents} from './act-two-components.mjs';
const dir='context/arcade/episode-two-v1',out='public/arcade/act-two/episode-two-v1';
await fs.mkdir(out,{recursive:true});await fs.mkdir(dir+'/sources',{recursive:true});
const manifest=JSON.parse(await fs.readFile(dir+'/art-sources.json','utf8')),registration={};
for(const item of manifest){
 if(!item.source)continue;
 const name=item.name==='castle-alpha'?'castle':item.name.replace(/-clean$/,''),source=dir+'/sources/'+item.name+'.png';
 try{await fs.access(source);}catch{await fs.copyFile(item.source,source);}
 if(['castle','interior','ring','hexy-double','harlequin-portrait','corn-sunset','corn-night'].includes(name)){
  if(name==='castle'&&item.name==='castle'&&manifest.some(q=>q.name==='castle-alpha'))continue;
  await sharp(source).webp({lossless:true}).toFile(out+'/'+name+'.webp');continue;
 }
 const rows=name.endsWith('-walk')?3:name==='rigging'?2:name==='minions'?6:4,count=rows*4,src=await spriteComponents(source),{data,info,labels}=src,side=512;
 let boxes;
 if(name==='effects')boxes=Array.from({length:16},(_,i)=>({left:Math.floor(i%4*info.width/4),top:Math.floor(Math.floor(i/4)*info.height/4),width:Math.floor(info.width/4),height:Math.floor(info.height/4),grid:true}));
 else{
  const bodies=src.components.toSorted((a,b)=>b.area-a.area).slice(0,count).sort((a,b)=>a.cy-b.cy);
  if(bodies.length!==count||bodies.at(-1).area<500)throw Error('Missing character cels: '+name);
  boxes=[];for(let row=0;row<rows;row++)boxes.push(...bodies.slice(row*4,row*4+4).sort((a,b)=>a.cx-b.cx));
 }
 const scale=name==='effects'?1:Math.min(430/Math.max(...boxes.map(q=>q.height)),486/Math.max(...boxes.map(q=>q.width)));
 const parts=[];registration[name]=[];
 for(const [frame,q]of boxes.entries()){
  let input,w,h;
  if(q.grid){w=440;h=440;input=await sharp(source).extract(q).resize(w,h,{fit:'contain'}).png().toBuffer();}
  else{
   const rgba=Buffer.alloc(q.width*q.height*4);
   // Mask by the whole connected body, so neighboring effects or stray pixels
   // cannot leak from the next drawing into this cel.
   for(let y=0;y<q.height;y++)for(let x=0;x<q.width;x++){
    const at=(y+q.top)*info.width+x+q.left;if(labels[at]!==q.id)continue;data.copy(rgba,(y*q.width+x)*4,at*4,at*4+4);
   }
   w=Math.round(q.width*scale);h=Math.round(q.height*scale);
   input=await sharp(rgba,{raw:{width:q.width,height:q.height,channels:4}}).resize(w,h).png().toBuffer();
  }
  const left=Math.round((side-w)/2),top=name==='effects'?Math.round((side-h)/2):499-h;
  parts.push({input,left:frame%4*side+left,top:Math.floor(frame/4)*side+top});
  const tip=name==='harlequin'?{x:left+w*(frame===5?.04:.19),y:top+h*(frame===5?.34:.22)}:{x:left+w*.06,y:top+h*.37};
  registration[name].push({source:q,scale,left,top,w,h,tip});
 }
 await sharp({create:{width:side*4,height:side*rows,channels:4,background:'#00000000'}}).composite(parts).webp({lossless:true}).toFile(out+'/'+name+'.webp');
}
await fs.writeFile(dir+'/registration.json',JSON.stringify(registration,null,2)+'\n');
const muzzles=Object.fromEntries(['harlequin','couple','minions'].filter(k=>registration[k]).map(k=>[k,registration[k].map(q=>[q.tip.x,q.tip.y])]));
await fs.writeFile('src/components/arcade/adventure/actors/bosses/episodeTwoRegistration.js','// Generated by pack-episode-two.mjs; whole characters, 512px cells.\nexport const EPISODE_TWO_MUZZLES='+JSON.stringify(muzzles)+';\n');
console.log('Episode-two assets packed:',manifest.map(q=>q.name).join(', '));
